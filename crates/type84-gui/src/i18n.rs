/// Strings for the current language.
pub fn s() -> &'static Strings {
    &RU
}

/// Replace `{name}` placeholders in a template.
pub fn fill(template: &str, args: &[(&str, &str)]) -> String {
    let mut out = template.to_string();
    for (k, v) in args {
        out = out.replace(&format!("{{{k}}}"), v);
    }
    out
}

/// Format millimetres the ru way, with a decimal comma ("2,00").
pub fn mm_comma(hundredths: u16) -> String {
    format!("{},{:02}", hundredths / 100, hundredths % 100)
}

/// Format millimetres with a decimal point, as the hub prints them on keycaps ("1.50").
pub fn mm_dot(hundredths: u16) -> String {
    format!("{}.{:02}", hundredths / 100, hundredths % 100)
}

/// Human name of an SOCD mode byte. Only mode 3 is verified on hardware
/// (PROTOCOL.md §3.3); the others print their raw number.
pub fn socd_mode(mode: u8) -> String {
    match mode {
        3 => "приоритет последнего ввода".to_string(),
        m => format!("режим {m}"),
    }
}

